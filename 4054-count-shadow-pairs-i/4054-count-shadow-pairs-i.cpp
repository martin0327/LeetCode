using ll = long long;
using vi = vector<ll>;
using vvi = vector<vi>;
using pii = pair<ll,ll>;
using vp = vector<pii>;
using vvp = vector<vp>;
using ti3 = tuple<ll,ll,ll>;
using vti3 = vector<ti3>;
using vs = vector<string>;

class Solution {
public:
    long long shadowPairs(vector<int>& aa) {
        vi a(aa.begin(), aa.end());
        int n = a.size();
        auto cx = get_unique(a);
        int sz = cx.size(); 
        auto fen = fenwick_tree<ll>(sz);
        auto g = [&] (ll x) {
            auto it = lower_bound(cx.begin(), cx.end(), x);
            return it - cx.begin();
        };
        ll ans = 0;
        vi st;
        for (auto x : a) {
            while (st.size()) {
                if (st.back() > x) {
                    auto y = g(st.back());
                    st.pop_back();
                    fen.add(y,-1);
                }
                else break;
            }
            auto idx = g(x);
            ans += fen.sum(0,idx);
            st.push_back(x);
            fen.add(g(x),1);
        }
        return ans;
    }
};